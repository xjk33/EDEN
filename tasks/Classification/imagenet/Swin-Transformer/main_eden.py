# --------------------------------------------------------
# EDEN 训练入口（SwinV2 分类）：在 main.py 的 baseline 流程上接入
# eden_adapter_swinv2 —— 模型封装、双优化器/双调度器、训练循环、
# checkpoint 均见 adapter 文件；本文件只做流程编排。
# 与 baseline 的差异仅限：模型多包一层 SwinV2WithDiffAE、优化器/调度器
# 换成双分支、训练循环换成 eden_train_one_epoch；数据、增广、task 侧
# 优化器与调度、验证路径均与 baseline 逐位一致。
#
# 用法：
#   python -m torch.distributed.launch --nproc_per_node 4 main_eden.py \
#       --cfg configs/swinv2/swinv2_tiny_patch4_window8_256_eden_tweight_mask.yaml \
#       --data-path <imagenet> --batch-size 128
# --------------------------------------------------------

import os
import time
import json
import random
import argparse
import datetime
import numpy as np

import torch
import torch.backends.cudnn as cudnn
import torch.distributed as dist

from timm.loss import LabelSmoothingCrossEntropy, SoftTargetCrossEntropy
from timm.utils import accuracy, AverageMeter

from config import get_config
